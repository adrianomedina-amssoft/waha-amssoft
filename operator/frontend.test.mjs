import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
const source = readFileSync(new URL('./app.js', import.meta.url), 'utf8');
async function browser(initialStatus, failStart = false) {
  let status = initialStatus; const calls = []; const timers = new Map(); let sequence = 0;
  const elements = {};
  for (const id of ['message','login','password','setup','setupqr','totp','code','panel','connection','start','refresh','pairqr','logout']) {
    elements[id] = { hidden: ['setup','totp','panel','pairqr'].includes(id), src: '', textContent: '', value: '', disabled: false, handlers: {}, addEventListener: function register(event, handler) { this.handlers[event] = handler; } };
  }
  const context = { document: { getElementById: function element(id) { return elements[id]; } }, location: { reload: function reload() {} },
    URL: { createObjectURL: function create() { return 'blob:fixture'; }, revokeObjectURL: function revoke() {} },
    setTimeout: function schedule(callback) { timers.set(++sequence,callback); return sequence; }, clearTimeout: function clear(id) { timers.delete(id); },
    fetch: async function request(path, options = {}) {
      calls.push((options.method || 'GET') + ' ' + path);
      if (path==='/auth/get-session') return Response.json({user:{twoFactorEnabled:true},session:{operatorMfa:true}});
      if (path==='/connection') return Response.json({status:status,number:null});
      if (path==='/connection/start') { if (failStart) return Response.json({error:'Não foi possível gerar um novo QR Code.'},{status:503}); status='SCAN_QR_CODE'; return Response.json({status:status}); }
      if (path==='/connection/qr') return new Response('<svg/>',{headers:{'Content-Type':'image/svg+xml'}});
      throw new Error('Unexpected fixture request');
    } };
  runInNewContext(source,context);
  await new Promise(resolve=>setImmediate(resolve));
  return { elements:elements,calls:calls,timers:timers,setStatus:function set(value){status=value;},
    click:async function click(id){await elements[id].handlers.click({preventDefault:function prevent(){}});},
    tick:async function tick(){const [id,callback]=timers.entries().next().value;timers.delete(id);await callback();} };
}
test('expired QR can be regenerated by either explicit button and polling stops after pairing',async function recovery() {
  for (const button of ['start','refresh']) {
    const page=await browser('FAILED');
    assert.match(page.elements.message.textContent,/expirou/);assert.equal(page.timers.size,0);
    await page.click(button);
    assert.equal(page.elements.pairqr.hidden,false);assert.equal(page.timers.size,1);
    assert.equal(page.calls.filter(value=>value==='POST /connection/start').length,1);
    page.setStatus('WORKING');await page.tick();
    assert.equal(page.timers.size,0);assert.equal(page.elements.pairqr.hidden,true);
    assert.equal(page.elements.connection.textContent,'WhatsApp conectado');
    assert.equal(page.calls.filter(value=>value==='POST /connection/start').length,1);
  }
});
test('starting session automatically displays QR without a manual refresh',async function starting() {
  const page=await browser('STARTING');assert.equal(page.elements.pairqr.hidden,true);assert.equal(page.timers.size,1);
  page.setStatus('SCAN_QR_CODE');await page.tick();
  assert.equal(page.elements.pairqr.hidden,false);assert.equal(page.timers.size,1);
  assert.equal(page.calls.some(value=>value.startsWith('POST')),false);
});
test('failed retry is displayed as a failure, not connection success',async function failure() {
  const page=await browser('FAILED',true);await page.click('start');
  assert.equal(page.elements.message.textContent,'Não foi possível gerar um novo QR Code.');
  assert.equal(page.elements.pairqr.hidden,true);assert.equal(page.elements.start.disabled,false);
});
